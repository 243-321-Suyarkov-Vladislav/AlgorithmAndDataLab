from collections import deque

def main():
    # 1. Создание пустой очереди
    q = deque()
    print("Очередь создана. Пуста?", len(q) == 0)

    # 2. Добавление элементов в очередь (Enqueue)
    print("\nДобавляем элементы: 'Задача 1', 'Задача 2', 'Задача 3'")
    q.append("Задача 1")
    q.append("Задача 2")
    q.append("Задача 3")

    # 3. Проверка размера и пустоты
    print(f"Размер очереди: {len(q)}")
    print("Очередь пуста?", len(q) == 0)

    # 4. Просмотр первого элемента без удаления
    print(f"Первый в очереди (без удаления): {q[0]}")

    # 5. Перебор элементов очереди (от начала к концу)
    print("Текущие элементы в очереди:", end=" ")
    for item in q:
        print(item, end=" | ")
    print()

    # 6. Получение элемента из очереди (Dequeue)
    print("\nИзвлекаем первый элемент...")
    item = q.popleft()
    print(f"Извлечен элемент: {item}")

    # 7. Проверка нового размера
    print(f"Новый размер очереди: {len(q)}")
    print(f"Теперь первый в очереди: {q[0]}")

    # 8. Очистка очереди
    q.clear()
    print("\nОчередь очищена. Пуста?", len(q) == 0)

if __name__ == "__main__":
    main()
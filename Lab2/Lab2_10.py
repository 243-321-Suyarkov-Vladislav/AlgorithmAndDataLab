colors = ["зеленой", "красной", "желтой", "белой", "черной"]
animals = ["крысы", "коровы", "тигра", "зайца", "дракона", "змеи",
           "лошади", "овцы", "обезьяны", "курицы", "собаки", "свиньи"]

year = int(input("Введите год: "))

# Смещение года относительно начала цикла (1984)
index = (year - 1984) % 60

color = colors[index // 12]   # каждые 12 лет меняется цвет
animal = animals[index % 12]  # каждые 12 лет проходят все животные

print("год", color, animal)
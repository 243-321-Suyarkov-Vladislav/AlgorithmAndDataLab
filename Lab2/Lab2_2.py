a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))
c = float(input("Введите третье число: "))

# Сортируем три числа по возрастанию вручную
if a > b:
    a, b = b, a          # теперь a <= b
if b > c:
    b, c = c, b          # теперь b <= c
if a > b:
    a, b = b, a          # окончательно a <= b <= c

result = b + c           # два наибольших — это b и c

print("Сумма двух наибольших =", result)
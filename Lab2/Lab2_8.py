teens = [
    "десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
    "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"
]
tens = ["", "", "двадцать", "тридцать", "сорок"]
units = ["", "одно", "два", "три", "четыре", "пять", "шесть", "семь", "восемь", "девять"]

n = int(input("Введите количество заданий (10-40): "))

if n < 20:
    word = teens[n - 10]
    # для 11-14 форма «заданий»
    if 11 <= n <= 14:
        form = "учебных заданий"
    else:
        form = "учебных заданий"
else:
    word = tens[n // 10]
    last = n % 10
    if last == 0:
        form = "учебных заданий"
    else:
        word += " " + units[last]
        if last == 1:
            form = "учебное задание"
        elif 2 <= last <= 4:
            form = "учебных задания"
        else:
            form = "учебных заданий"

print(word, form)
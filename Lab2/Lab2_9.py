hundreds = ["", "сто", "двести", "триста", "четыреста",
            "пятьсот", "шестьсот", "семьсот", "восемьсот", "девятьсот"]
tens = ["", "", "двадцать", "тридцать", "сорок",
        "пятьдесят", "шестьдесят", "семьдесят", "восемьдесят", "девяносто"]
units = ["", "один", "два", "три", "четыре", "пять",
         "шесть", "семь", "восемь", "девять"]
teens = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
         "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]

n = int(input("Введите число от 100 до 999: "))

h = n // 100
rem = n % 100

parts = [hundreds[h]]

if rem == 0:
    pass
elif rem < 10:
    parts.append(units[rem])
elif rem < 20:
    parts.append(teens[rem - 10])
else:
    parts.append(tens[rem // 10])
    if rem % 10 != 0:
        parts.append(units[rem % 10])

print(" ".join(parts))
def insertion_sort(arr):
    # 1. Начинаем со второго элемента (индекс 1), так как первый уже "отсортирован"
    for i in range(1, len(arr)):
        key = arr[i] # Запоминаем текущий элемент
        j = i - 1    # Начинаем сравнивать с элементом слева
        
        # 2. Сдвигаем элементы, которые больше key, вправо
        while j >= 0 and arr[j] > key:
            arr[j + 1] = arr[j]
            j -= 1
            
        # 3. Вставляем key на освободившееся место
        arr[j + 1] = key
        
    return arr

# Проверка
numbers = [3, 44, 38, 5, 47, 15, 36, 26, 27, 2, 46, 4, 19, 50, 48]
print("Отсортированный массив:", insertion_sort(numbers))
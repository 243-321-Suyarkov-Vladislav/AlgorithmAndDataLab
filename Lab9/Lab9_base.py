def selection_sort(arr):
    n = len(arr)
    
    # 1. Перебираем массив от первого элемента до предпоследнего
    for i in range(n - 1):
        # 2. Текущий элемент считаем наименьшим
        min_idx = i
        
        # 3. Проходимся по оставшейся неотсортированной части
        for j in range(i + 1, n):
            # 4. Если найден элемент меньше текущего минимума — обновляем индекс
            if arr[j] < arr[min_idx]:
                min_idx = j
                
        # 5. Меняем местами текущий элемент с наименьшим (если они различаются)
        if min_idx != i:
            arr[i], arr[min_idx] = arr[min_idx], arr[i]
            
    return arr

# Проверка работы
numbers = [3, 44, 38, 5, 47, 15, 36, 26, 27, 2, 46, 4, 19, 50, 48]
print("Отсортированный массив:", selection_sort(numbers))